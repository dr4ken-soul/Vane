/**
 * Builds the Noir test vector for the CBAM attestation circuit.
 *
 * The script derives the supplier tax identifier hash, the allocation Merkle tree and the invoice
 * nullifier with the same TypeScript code the browser uses, then writes the Noir `Prover.toml`
 * file and a JSON fixture consumed by the Hardhat contract tests.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";
import {
  buildAllocationTree,
  computeInvoiceNullifier,
  hashAllocationLeaf,
  leafSalt,
  splitCleanAllocations,
} from "../src/lib/noir/energyMerkle";
import { fromHex32, toHex32 } from "../src/lib/noir/poseidon2";
import { hashInvoiceSerial, hashTaxId } from "../src/lib/noir/taxIdHash";

const SUPPLIER_TAX_ID = "TR4810923811";
const INVOICE_SERIAL = "GZB-2026-000481";
const CLEAN_KWH = 41800;
const GRID_KWH = 12840;
const DIRECT_EMISSIONS_KG = 257410;
const SHIPMENT_MASS_TONNES = 185;
const GRID_FACTOR_G_PER_KWH = 412;
const MAX_INTENSITY_KG_PER_TONNE = 1450;
const CN_COMMODITY_CODE = 7208;
const UNIT_PRICE_EUR_CENTS = 64250;

// Sibling slots of the settlement batch. The test vector keeps them fixed so the fixture stays
// reproducible, while the browser derives them from the live facility window.
const BATCH_TOTAL_CLEAN_KWH = 268640;
const SIBLING_SLOTS = splitCleanAllocations(BATCH_TOTAL_CLEAN_KWH, 15);

const supplierTaxIdHash = hashTaxId(SUPPLIER_TAX_ID);
const invoiceSerialSecret = hashInvoiceSerial(INVOICE_SERIAL);

const allocations = [
  { index: 0, kwh: CLEAN_KWH, salt: leafSalt(0) },
  ...SIBLING_SLOTS.map((slot) => ({ index: slot.index + 1, kwh: slot.kwh, salt: leafSalt(slot.index + 1) })),
];

const tree = buildAllocationTree(allocations, supplierTaxIdHash);
const provenLeaf = tree.leaves[0];
const nullifier = computeInvoiceNullifier(supplierTaxIdHash, invoiceSerialSecret, CLEAN_KWH);

const field = (value: bigint): string => `"0x${toHex32(value)}"`;

const proverToml = [
  "# Test vector for the Vane CBAM attestation circuit.",
  "# Generated by scripts/buildProverToml.ts so the Noir witness and the browser prover agree.",
  "",
  `unit_price_eur_cents = "${UNIT_PRICE_EUR_CENTS}"`,
  `supplier_tax_id_hash = ${field(supplierTaxIdHash)}`,
  `invoice_serial_secret = ${field(invoiceSerialSecret)}`,
  `clean_kwh_allocated = "${CLEAN_KWH}"`,
  `grid_kwh_allocated = "${GRID_KWH}"`,
  `direct_process_emissions_kg = "${DIRECT_EMISSIONS_KG}"`,
  `shipment_mass_tonnes = "${SHIPMENT_MASS_TONNES}"`,
  `grid_emission_factor_g_per_kwh = "${GRID_FACTOR_G_PER_KWH}"`,
  `merkle_leaf_salt = ${field(provenLeaf.salt)}`,
  `merkle_path = [${provenLeaf.path.map((value) => field(value)).join(", ")}]`,
  `merkle_indices = [${provenLeaf.indices.map((index) => (index === 0 ? "false" : "true")).join(", ")}]`,
  `facility_merkle_root = ${field(tree.root)}`,
  `invoice_nullifier = ${field(nullifier)}`,
  `max_intensity_kg_per_tonne = "${MAX_INTENSITY_KG_PER_TONNE}"`,
  `cn_commodity_code = "${CN_COMMODITY_CODE}"`,
  "",
].join("\n");

const REPO_ROOT = resolve(process.cwd(), "..");

const proverPath = resolve(REPO_ROOT, "circuits", "cbam_attestation", "Prover.toml");
writeFileSync(proverPath, proverToml, "utf8");

const fixture = {
  description: "Vane CBAM attestation test vector generated from the Gebze hot rolled coil invoice.",
  supplierTaxIdHash: toHex32(supplierTaxIdHash),
  invoiceSerialSecret: toHex32(invoiceSerialSecret),
  merkleRoot: toHex32(tree.root),
  invoiceNullifier: toHex32(nullifier),
  publicInputs: [
    toHex32(tree.root),
    toHex32(nullifier),
    toHex32(BigInt(MAX_INTENSITY_KG_PER_TONNE)),
    toHex32(BigInt(CN_COMMODITY_CODE)),
  ],
  cleanKwhAllocated: CLEAN_KWH,
  leafIndex: 0,
  allocationSlots: allocations.map((slot) => ({ index: slot.index, kwh: slot.kwh })),
  leafHash: toHex32(hashAllocationLeaf(CLEAN_KWH, supplierTaxIdHash, leafSalt(0))),
  siblingRoot: toHex32(fromHex32(toHex32(tree.root))),
};

const fixturePath = resolve(REPO_ROOT, "contracts", "test", "fixtures", "proofFixture.json");
mkdirSync(resolve(fixturePath, ".."), { recursive: true });
writeFileSync(fixturePath, `${JSON.stringify(fixture, null, 2)}\n`, "utf8");

console.log(`Wrote ${proverPath}`);
console.log(`Wrote ${fixturePath}`);
console.log(`Merkle root: 0x${toHex32(tree.root)}`);
console.log(`Nullifier:   0x${toHex32(nullifier)}`);
